// Maps action groups to their corresponding icon components
export function getGroupIcon(group, props = {}) {
  switch (group?.toLowerCase()) {
    case 'dashboard':
      return <DashboardIcon {...props} />;
    case 'profile':
      return <ProfileIcon {...props} />;
    case 'charging':
      return <ChargingIcon {...props} />;
    case 'payment':
      return <PaymentIcon {...props} />;
    case 'operations':
      return <OperationsIcon {...props} />;
    case 'maintenance':
      return <MaintenanceIcon {...props} />;
    case 'business':
      return <BusinessIcon {...props} />;
    case 'franchise':
      return <FranchiseIcon {...props} />;
    case 'admin':
      return <AdminIcon {...props} />;
    case 'reports':
      return <ReportIcon {...props} />;
    default:
      return <BoltIcon {...props} />;
  }
}
